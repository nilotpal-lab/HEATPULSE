/**
 * Retrieves metadata for a state by canonical ID, case-insensitively.
 */
export function getIndianStateMetadata(stateId: string): IndianStateMetadata | undefined {
  if (!stateId) return undefined;
  const canonical = stateId.toLowerCase().trim().replace(/[\s-]+/g, '_') as IndianStateId;
  return INDIAN_STATES_METADATA[canonical];
}

/**
 * Resolves a GeoJSON feature state name to its corresponding IndianStateMetadata.
 */
export function findStateByGeoJsonName(geoJsonName: string): IndianStateMetadata | undefined {
  if (!geoJsonName) return undefined;
  const target = geoJsonName.trim().toUpperCase();
  return INDIAN_STATES_LIST.find((s) => s.geoJsonState.toUpperCase() === target);
}

